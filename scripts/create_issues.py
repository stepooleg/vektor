def create_one(issue: dict, dry: bool) -> str | None:
    title = issue["title"]
    if dry:
        labels = ",".join(issue["labels"])
        print(f"  [DRY] {title}  [{labels}]  → {issue['milestone']}")
        return None
    args = [
        "gh", "issue", "create", "--repo", REPO,
        "--title", title,
        "--body", issue["body"],
        "--milestone", issue["milestone"],
    ]
    for lab in issue["labels"]:
        args += ["--label", lab]
    res = subprocess.run(args, capture_output=True, text=True, encoding="utf-8")
    if res.returncode != 0:
        sys.stderr.write(f"❌ '{title}': {res.stderr.strip()}\n")
        return None
    url = res.stdout.strip()
    num = url.rsplit("/", 1)[-1]
    print(f"  ✅ #{num}  {title}")
    return num


def main():
    ap = argparse.ArgumentParser(description="Создание issues Vektor по фазам")
    ap.add_argument("--dry-run", action="store_true", help="Не создавать, только показать")
    ap.add_argument("--list", action="store_true", help="Только вывести сводку")
    args = ap.parse_args()

    all_issues = ISSUES + OPEN_QUESTIONS
    print(f"\n📋 Всего issues к созданию: {len(all_issues)}")
    print(f"   Фазы (MVP+): {len(ISSUES)} | Открытые вопросы §17: {len(OPEN_QUESTIONS)}\n")

    if args.list:
        for i, it in enumerate(all_issues, 1):
            print(f"  {i:2}. [{it['milestone']}] {it['title']}")
        return

    created = 0
    for it in all_issues:
        if create_one(it, args.dry_run) is not None or args.dry_run:
            created += 1

    print(f"\n{'Показано (dry-run)' if args.dry_run else 'Создано'}: {created}\n")
    print("Ссылки:")
    print(f"  Issues:      https://github.com/{REPO}/issues")
    print(f"  Milestones:  https://github.com/{REPO}/milestones")


if __name__ == "__main__":
    main()
