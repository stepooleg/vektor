AGENTS = "https://github.com/stepooleg/vektor/blob/main/AGENTS.md"


def spec(sec: str) -> str:
    return f"[SPEC §{sec}]({SPEC})"


def bb(sec: str) -> str:
    return f"[BRANDBOOK §{sec}]({BB})"


def dedent(s: str) -> str:
    return textwrap.dedent(s).strip("\n")


DOD = dedent("""
    ## ✅ Definition of Done ([AGENTS.md §10](%s))

    - [ ] Тесты написаны **до** реализации и проходят
    - [ ] Реализация соответствует SPEC/BRANDBOOK
    - [ ] `ruff` / `mypy` (BE), `eslint` / `tsc` (FE) — зелёные
    - [ ] CI зелёный
    - [ ] Если UI — проверено в светлой и тёмной темах (хардкод-цветов нет)
    - [ ] Если затронуты ПДн/анонимность/права — покрыто тестами
    - [ ] Документация/докстринги обновлены
""") % AGENTS


def body(*, context: str, tasks: list[str], tests: list[str] | None = None,
         notes: str = "") -> str:
    parts = [f"## 📌 Контекст\n\n{context}\n"]
    parts.append("## 🎯 Задачи\n")
    for t in tasks:
        parts.append(f"- [ ] {t}")
    parts.append("")
    if tests:
        parts.append("## 🧪 Test-First — тесты пишутся первыми\n")
        for t in tests:
            parts.append(f"- [ ] {t}")
        parts.append("")
    if notes:
        parts.append(f"## ⚠️ Особые требования\n\n{notes}\n")
    parts.append(DOD)
    return "\n".join(parts)


