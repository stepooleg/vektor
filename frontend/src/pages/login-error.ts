import type { ApiError } from "@/api/client";

/** Безопасное и полезное сообщение для основных классов ошибок входа. */
export function getLoginErrorMessage(error: ApiError): string {
  if (error.status === 401) {
    return "Неверный email или пароль. Проверьте данные и попробуйте снова.";
  }
  if (error.status === 429) {
    return "Слишком много попыток входа. Подождите несколько минут и попробуйте снова.";
  }
  if (error.status === 0) {
    return "Не удалось связаться с сервисом. Проверьте подключение и попробуйте снова.";
  }
  if (error.status >= 500) {
    return "Сервис временно недоступен. Попробуйте войти позже.";
  }
  return "Не удалось выполнить вход. Попробуйте снова или обратитесь к администратору.";
}
